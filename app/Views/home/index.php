        // Load YouTube IFrame API
        const tag = document.createElement('script');
        tag.src = "https://www.youtube.com/iframe_api";
        const firstScriptTag = document.getElementsByTagName('script')[0];
        firstScriptTag.parentNode.insertBefore(tag, firstScriptTag);

        window.onYouTubeIframeAPIReady = function() {
            // API Loaded
        };

        function openModal(videoId, videoType, videoUrl) {
            overlay.classList.remove('hidden');
            // Force reflow
            void overlay.offsetWidth; 
            overlay.classList.remove('opacity-0');
            container.classList.remove('scale-95');
            container.classList.add('scale-100');
            
            if (videoType === 'mp4') {
                // Hide YouTube, Show HTML5
                if (player && player.stopVideo) player.stopVideo();
                youtubeContainer.classList.add('hidden');
                html5Player.classList.remove('hidden');
                html5Player.src = videoUrl;
                html5Player.play().catch(e => console.log('Autoplay blocked:', e));
            } else {
                // Hide HTML5, Show YouTube
                html5Player.pause();
                html5Player.classList.add('hidden');
                youtubeContainer.classList.remove('hidden');
                
                if (player) {
                    player.loadVideoById(videoId);
                } else {
                    player = new YT.Player('youtube-player', {
                        height: '100%',
                        width: '100%',
                        videoId: videoId,
                        playerVars: {
                            'autoplay': 1,
                            'rel': 0,
                            'modestbranding': 1
                        },
                        events: {
                            'onReady': onPlayerReady
                        }
                    });
                }
            }
            
            document.body.style.overflow = 'hidden'; // Prevent scrolling
        }

        function onPlayerReady(event) {
            event.target.playVideo();
        }

        function closeModal() {
            overlay.classList.add('opacity-0');
            container.classList.remove('scale-100');
            container.classList.add('scale-95');
            
            setTimeout(() => {
                overlay.classList.add('hidden');
                
                // Stop YouTube
                if (player && player.stopVideo) {
                    player.stopVideo();
                }
                
                // Stop HTML5
                html5Player.pause();
                html5Player.currentTime = 0;
                html5Player.src = ""; // Clear source to stop buffering
                
                document.body.style.overflow = '';
            }, 300);
        }

        // Event Listeners
        triggers.forEach(trigger => {
            trigger.addEventListener('click', function(e) {
                const videoId = this.getAttribute('data-video-id');
                const videoUrl = this.getAttribute('data-video-url');
                const videoType = this.getAttribute('data-video-type') || 'youtube';
                
                if (videoId || videoUrl) {
                    openModal(videoId, videoType, videoUrl);
                }
            });
        });

        closeBtn.addEventListener('click', closeModal);

        // Close on click outside
        overlay.addEventListener('click', function(e) {
            if (e.target === overlay) {
                closeModal();
            }
        });

        // Close on Escape key
        document.addEventListener('keydown', function(e) {
            if (e.key === 'Escape' && !overlay.classList.contains('hidden')) {
                closeModal();
            }
        });
    });
